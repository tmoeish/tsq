// GenCmd generates tsq table, result, and DDL artifacts for a package.
var GenCmd = &cobra.Command{
	Use:   "gen <package-or-dir>",
	Short: "Generate *.tsq.go files for one Go package",
	Long: `Generate TSQ code for one Go package.

Accepted inputs:
  - module import path: github.com/acme/project/internal/database
  - relative directory: ./internal/database
  - absolute directory: /path/to/project/internal/database

Generated files:
  - <struct>.tsq.go for each @TABLE struct
  - <result>.result.tsq.go for each @RESULT struct
  - sqlite.sql / mysql.sql / postgres.sql beside generated Go files
    with the initial schema plus dated migration sections
  - tsq.json with the latest snapshot and migration history

Overwrite behavior:
  - creates missing generated files
  - atomically replaces existing generated files that start with
    "Code generated by tsq-"
  - refuses to overwrite non-generated files

 Troubleshooting:
  - run from the module root when using a relative directory
  - ensure the target package loads and contains Go files
  - use -v to print each rendered file path
  - after generation, execute the SQL file matching your live database dialect
  - generator validation errors point to the offending struct or field`,
	Example: strings.Join([]string{
		"  tsq gen ./examples/academy",
		"  tsq gen --dry-run ./examples/academy",
		"  tsq gen --check github.com/tmoeish/tsq/v5/examples/academy",
		"  tsq gen github.com/tmoeish/tsq/v5/examples/academy",
	}, "\n"),
	Args: exactOnePackageArg,
	RunE: func(cmd *cobra.Command, args []string) error {
		if dryRunFlag && checkFlag {
			return errors.New("--dry-run and --check cannot be used together")
		}

		tableTpl, resultTpl, runtimeTplText := defaultTableTpl, defaultResultTpl, defaultRuntimeTpl

		pPath := args[0]
		errWriter := cmd.ErrOrStderr()

		list, dir, err := parser.Parse(pPath)
		if err != nil {
			return err
		}

		for i := range list {
			list[i].SetTSQVersion(stableVersion(buildinfo.Version()))
		}

		tpl, err := template.New("table.go.tmpl").Funcs(funcMap()).Parse(tableTpl)
		if err != nil {
			return fmt.Errorf("%s: %w", "failed to parse table template", err)
		}

		resultTplParsed, err := template.New("result.go.tmpl").Funcs(funcMap()).Parse(resultTpl)
		if err != nil {
			return fmt.Errorf("%s: %w", "failed to parse Result template", err)
		}

		runtimeTplParsed, err := template.New("runtime.go.tmpl").Funcs(funcMap()).Parse(runtimeTplText)
		if err != nil {
			return fmt.Errorf("%s: %w", "failed to parse runtime template", err)
		}

		models, err := buildGenerationModels(list, dir, tpl, resultTplParsed, runtimeTplParsed)
		if err != nil {
			return err
		}

		stats := summarizeGenerationModels(models)
		if v {
			_, _ = fmt.Fprintf(errWriter, "parsed %d table(s), %d result(s)\n", stats.Tables, stats.Results)
		}

		plan, err := buildGenerationPlan(models, dir)
		if err != nil {
			return err
		}

		ddlArtifacts, err := buildDDLArtifacts(pPath, list, dir)
		if err != nil {
			return err
		}

		ddlPlan, err := buildDDLPlan(ddlArtifacts.models, dir)
		if err != nil {
			return err
		}

		combinedPlan := appendCombinedGenerationPlans(plan, ddlPlan)

		if dryRunFlag {
			printGenerationPlan(cmd.OutOrStdout(), combinedPlan)

			if v {
				printDDLChangeSummary(errWriter, ddlArtifacts)
				printGenerationSummary(errWriter, combinedPlan)
			}

			return nil
		}

		if checkFlag {
			if v {
				printDDLChangeSummary(errWriter, ddlArtifacts)
				printGenerationSummary(errWriter, combinedPlan)
			}

			if err := ensureGenerationPlanUpToDate(combinedPlan); err != nil {
				return err
			}

			return nil
		}

		for _, model := range models {
			if err := renderGenerationModel(model); err != nil {
				return err
			}
		}

		for _, model := range ddlArtifacts.models {
			if v {
				if _, err := fmt.Fprintf(errWriter, "ddl %s\n", model.Filename); err != nil {
					return err
				}
			}

			if err := writeDDLFile(model.Filename, model.Source); err != nil {
				return fmt.Errorf("failed to write DDL file: %s"+": %w", model.Filename, err)
			}
		}

		for _, entry := range ddlPlan {
			if entry.Status != generationPlanStale {
				continue
			}

			if err := os.Remove(entry.Filename); err != nil && !os.IsNotExist(err) {
				return fmt.Errorf("failed to remove stale DDL file: %s"+": %w", entry.Filename, err)
			}
		}

		if err := printDDLGuidance(errWriter, ddlArtifacts); err != nil {
			return err
		}

		if v {
			printDDLChangeSummary(errWriter, ddlArtifacts)
			printGenerationSummary(errWriter, combinedPlan)
		}

		return nil
	},
}

func appendCombinedGenerationPlans(plans ...[]generationPlanEntry) []generationPlanEntry {
	total := 0
	for _, plan := range plans {
		total += len(plan)
	}

	combined := make([]generationPlanEntry, 0, total)
	for _, plan := range plans {
		combined = append(combined, plan...)
	}

	sort.Slice(combined, func(i, j int) bool {
		return combined[i].Filename < combined[j].Filename
	})

	return combined
}

func printDDLGuidance(w io.Writer, artifacts ddlArtifacts) error {
	if !artifacts.firstRun && !artifacts.hasChange {
		return nil
	}

	label := maybeANSI(w, ansiBoldCyan, "DDL")
	filename := "<dialect>.sql"
	action := "execute the full schema file matching your database dialect"

	if !artifacts.firstRun {
		action = "execute the latest dated schema section in the file matching your database dialect"
	}

	paths := make([]string, 0, len(ddlDialects))
	for _, dialect := range ddlDialects {
		name := ddlDialectName(dialect)
		paths = append(paths, fmt.Sprintf("%s=%s", name, strings.Replace(filename, "<dialect>", name, 1)))
	}

	if _, err := fmt.Fprintf(w, "%s: %s: %s\n",
		label,
		action,
		strings.Join(paths, " "),
	); err != nil {
		return err
	}

	return nil
}

func printDDLChangeSummary(w io.Writer, artifacts ddlArtifacts) {
	if !artifacts.hasChange {
		if _, err := fmt.Fprintf(w, "%s: no schema changes\n", maybeANSI(w, ansiBoldCyan, "ddl")); err != nil {
			return
		}

		return
	}

	if _, err := fmt.Fprintf(w, "%s:\n", maybeANSI(w, ansiBoldCyan, "ddl")); err != nil {
		return
	}

	for _, table := range artifacts.recordTables {
		if _, err := fmt.Fprintf(w, "  <%s>:\n", maybeANSI(w, ansiBold, table.Table)); err != nil {
			return
		}

		if len(table.Columns) == 1 && len(table.Indexes) == 0 && isDDLTableLine(table.Columns[0]) {
			if _, err := fmt.Fprintf(w, "    %s\n", colorizeDDLAction(w, table.Columns[0])); err != nil {
				return
			}

			continue
		}

		if len(table.Columns) > 0 {
			if _, err := fmt.Fprintf(w, "    %s:\n", maybeANSI(w, ansiCyan, "columns")); err != nil {
				return
			}

			for _, line := range table.Columns {
				if _, err := fmt.Fprintf(w, "      %s\n", colorizeDDLAction(w, line)); err != nil {
					return
				}
			}
		}

		if len(table.Indexes) > 0 {
			if _, err := fmt.Fprintf(w, "    %s:\n", maybeANSI(w, ansiCyan, "indexes")); err != nil {
				return
			}

			for _, line := range table.Indexes {
				if _, err := fmt.Fprintf(w, "      %s\n", colorizeDDLAction(w, line)); err != nil {
					return
				}
			}
		}
	}
}

func isDDLTableLine(line string) bool {
	return line == "create table" || line == "drop table"
}

func colorizeDDLAction(w io.Writer, line string) string {
	if !isTerminalWriter(w) {
		return line
	}

	action, rest, ok := strings.Cut(line, " ")
	if !ok {
		return line
	}

	switch action {
	case "create", "add":
		return ansiGreen + action + ansiReset + " " + rest
	case "alter":
		return ansiYellow + action + ansiReset + " " + rest
	case "drop":
		return ansiRed + action + ansiReset + " " + rest
	default:
		return line
	}
}

func maybeANSI(w io.Writer, code, text string) string {
	if !isTerminalWriter(w) {
		return text
	}

	return code + text + ansiReset
}

func isTerminalWriter(w io.Writer) bool {
	type fdWriter interface {
		Fd() uintptr
	}

	fd, ok := w.(fdWriter)
	if !ok {
		return false
	}

	return term.IsTerminal(int(fd.Fd()))
}

func exactOnePackageArg(_ *cobra.Command, args []string) error {
	return exactOnePackageArgFor("gen")(nil, args)
}

func exactOnePackageArgFor(command string) cobra.PositionalArgs {
	return func(_ *cobra.Command, args []string) error {
		if len(args) == 1 {
			return nil
		}

		return fmt.Errorf("tsq %s expects exactly one package path, got %d", command, len(args))
	}
}

func validateStructForGeneration(
	data *genmodel.StructInfo,
	structsByName map[string]*genmodel.StructInfo,
) error {
	if data == nil || data.TableMeta == nil {
		return nil
	}

	if data.IsResult {
		return validateResultFields(data, structsByName)
	}

	if err := validatePrimaryKeyField(data); err != nil {
		return err
	}

	if err := validateVersionField(data); err != nil {
		return err
	}

	if err := validateFieldDatabaseCompatibility(data); err != nil {
		return err
	}

	if err := validateIdentifierLengths(data); err != nil {
		return err
	}

	return validateManagedFields(data)
}

// generatedDialects are the dialects tsq gen writes DDL for; every identifier must
// fit all of them.
var generatedDialects = []tsqdialect.Dialect{
	tsqdialect.MySQLDialect{},
	tsqdialect.PostgresDialect{},
	tsqdialect.SQLiteDialect{},
}

// validateIdentifierLengths rejects names a dialect would truncate. The runtime
// rejects them too, but only when it starts; derived index names are the usual
// culprit and are cheapest to fix here, where the directive can name them.
func validateIdentifierLengths(data *genmodel.StructInfo) error {
	check := func(kind, name, fix string) error {
		for _, d := range generatedDialects {
			if err := tsqdialect.ValidateIdentifier(d, name); err != nil {
				return fmt.Errorf("%s %s of %s: %w; %s", kind, name, data.TypeInfo.TypeName, err, fix)
			}
		}

		return nil
	}

	if err := check("table", data.Table, "set a shorter name with //tsq:table name=..."); err != nil {
		return err
	}

	for _, field := range data.Fields {
		if err := check("column", field.Column, "shorten the db tag of field "+field.Name); err != nil {
			return err
		}
	}

	for _, group := range []struct {
		directive string
		indexes   []genmodel.IndexInfo
	}{{"unique", data.Uniques}, {"index", data.Indexes}} {
		for _, index := range group.indexes {
			fix := fmt.Sprintf("name it explicitly: //tsq:%s %s name=...", group.directive, strings.Join(index.Fields, ","))
			if err := check("index", index.Name, fix); err != nil {
				return err
			}
		}
	}

	return nil
}

func validateResultFields(
	dto *genmodel.StructInfo,
	structsByName map[string]*genmodel.StructInfo,
) error {
	normalizedRefs := make(map[string]string, len(dto.Fields))

	for _, field := range dto.Fields {
		parts := strings.Split(field.Column, ".")
		if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
			return fmt.Errorf(
				"result field %s must reference a generated column as Struct.Field, got %q",
				field.Name,
				field.Column,
			)
		}

		normalizedRef := strings.ReplaceAll(field.Column, ".", "_")
		if existing, ok := normalizedRefs[normalizedRef]; ok && existing != field.Column {
			return fmt.Errorf(
				"result field %s reference %s collides with %s after normalization",
				field.Name,
				field.Column,
				existing,
			)
		}

		normalizedRefs[normalizedRef] = field.Column

		targetStruct, ok := structsByName[parts[0]]
		if !ok || targetStruct.TableMeta == nil {
			return fmt.Errorf(
				"result field %s references unknown struct %s",
				field.Name,
				parts[0],
			)
		}

		sourceField, ok := targetStruct.FieldsByName[parts[1]]
		if !ok {
			return fmt.Errorf(
				"result field %s references unknown field %s.%s",
				field.Name,
				parts[0],
				parts[1],
			)
		}

		if !isScanCompatible(field, sourceField) {
			return fmt.Errorf(
				"result field %s type %s is incompatible with %s.%s type %s",
				field.Name,
				field.String(),
				parts[0],
				parts[1],
				sourceField.String(),
			)
		}
	}

	return nil
}

func isScanCompatible(dst, src genmodel.FieldInfo) bool {
	return dst.Type == src.Type &&
		dst.IsPointer == src.IsPointer &&
		dst.IsSlice == src.IsSlice
}

func normalizeResultColumns(data *genmodel.StructInfo) {
	for i, field := range data.Fields {
		field.Column = strings.ReplaceAll(field.Column, ".", "_")
		data.Fields[i] = field

		mapped := data.FieldsByName[field.Name]
		mapped.Column = field.Column
		data.FieldsByName[field.Name] = mapped
	}
}

func validateGeneratedFilenameCollisions(list []*genmodel.StructInfo) error {
	seen := make(map[string]string, len(list))

	for _, data := range list {
		if data == nil || data.TableMeta == nil || len(data.Fields) == 0 {
			continue
		}

		filename := generatedFilename(data)
		if existing, ok := seen[filename]; ok && existing != data.TypeInfo.TypeName {
			return fmt.Errorf(
				"generated filename %s collides between %s and %s",
				filename,
				existing,
				data.TypeInfo.TypeName,
			)
		}

		seen[filename] = data.TypeInfo.TypeName
	}

	return nil
}

func validateIndexNameCollisions(list []*genmodel.StructInfo) error {
	type definition struct {
		table  string
		fields string
		unique bool
	}

	seen := make(map[string]definition)

	for _, data := range list {
		if data == nil || data.TableMeta == nil || data.IsResult {
			continue
		}

		for _, group := range []struct {
			unique bool
			items  []genmodel.IndexInfo
		}{
			{unique: true, items: data.Uniques},
			{unique: false, items: data.Indexes},
		} {
			for _, idx := range group.items {
				current := definition{
					table:  data.Table,
					fields: strings.Join(idx.Fields, ","),
					unique: group.unique,
				}

				existing, ok := seen[idx.Name]
				if !ok {
					seen[idx.Name] = current
					continue
				}

				if existing == current {
					return fmt.Errorf(
						"duplicate index name %s on table %s",
						idx.Name,
						data.Table,
					)
				}

				return fmt.Errorf(
					"index name %s collides between %s(%s) and %s(%s)",
					idx.Name,
					existing.table,
					existing.fields,
					current.table,
					current.fields,
				)
			}
		}
	}

	return nil
}

func validateGeneratedSymbolCollisions(list []*genmodel.StructInfo) error {
	seen := make(map[string]string)

	register := func(symbol, owner string) error {
		if symbol == "" {
			return nil
		}

		if existing, ok := seen[symbol]; ok && existing != owner {
			return fmt.Errorf("generated symbol %s collides between %s and %s", symbol, existing, owner)
		}

		seen[symbol] = owner

		return nil
	}

	for _, data := range list {
		if data == nil || data.TableMeta == nil {
			continue
		}

		typeName := data.TypeInfo.TypeName
		symbols := []string{typeName + "__Cols"}

		for _, field := range data.Fields {
			symbols = append(symbols, typeName+"_"+field.Name)
		}

		if !data.IsResult {
			symbols = append(symbols,
				"tsq"+typeName+"Table",
				"Table"+typeName,
				"Query"+typeName,
				"Query"+typeName+"By"+data.PrimaryKey,
				"Query"+typeName+"By"+data.PrimaryKey+"In",
				"Fetch"+typeName+"By"+data.PrimaryKey,
			)

			for _, ux := range data.Uniques {
				symbols = append(symbols,
					"Query"+typeName+"By"+joinAnd(ux.Fields),
					"Query"+typeName+"By"+joinAnd(ux.Fields)+"In",
					"Fetch"+typeName+"By"+joinAnd(ux.Fields),
				)
			}
		}

		for _, symbol := range symbols {
			if err := register(symbol, typeName); err != nil {
				return err
			}
		}
	}

	return nil
}

func generatedFilename(data *genmodel.StructInfo) string {
	base := strings.ToLower(data.TypeInfo.TypeName)
	if data.IsResult {
		return fmt.Sprintf("%s.result.tsq.go", base)
	}

	return fmt.Sprintf("%s.tsq.go", base)
}

func validatePrimaryKeyField(data *genmodel.StructInfo) error {
	if data == nil || data.TableMeta == nil || data.PrimaryKey == "" {
		return nil
	}

	field, ok := data.FieldsByName[data.PrimaryKey]
	if !ok {
		return fmt.Errorf("id field %s not found in %s", data.PrimaryKey, data.TypeInfo.TypeName)
	}

	if field.IsPointer || field.IsSlice {
		return fmt.Errorf(
			"id field %s in %s cannot be a pointer or slice/array type",
			data.PrimaryKey,
			data.TypeInfo.TypeName,
		)
	}

	return nil
}

func validateVersionField(data *genmodel.StructInfo) error {
	if data == nil || data.TableMeta == nil || data.VersionField == "" {
		return nil
	}

	field, ok := data.FieldsByName[data.VersionField]
	if !ok {
		return fmt.Errorf("version field %s not found in %s", data.VersionField, data.TypeInfo.TypeName)
	}

	if !isIntegerFieldType(field) || field.IsPointer || field.IsSlice {
		return fmt.Errorf("version field %s in %s must be a non-pointer integer type", data.VersionField, data.TypeInfo.TypeName)
	}

	return nil
}

func validateFieldDatabaseCompatibility(data *genmodel.StructInfo) error {
	if data == nil || data.TableMeta == nil {
		return nil
	}

	keywordFields := make(map[string]struct{}, len(data.SearchColumns))
	for _, field := range data.SearchColumns {
		keywordFields[field] = struct{}{}
	}

	for _, field := range data.Fields {
		if err := validateFieldDatabaseType(field, keywordFields); err != nil {
			return fmt.Errorf("field %s in %s"+": %w", field.Name, data.TypeInfo.TypeName, err)
		}
	}

	return nil
}

// validateDatabaseFilledFields refuses a column the database fills where TSQ has
// to write the value itself.
func validateDatabaseFilledFields(data *genmodel.StructInfo) error {
	managed := map[string]string{
		data.PrimaryKey:     "the primary key",
		data.VersionField:   "the version column",
		data.CreatedAtField: "created_at",
		data.UpdatedAtField: "updated_at",
		data.DeletedAtField: "deleted_at",
	}

	for _, column := range data.Schema {
		if column.Fill == "" {
			continue
		}

		for _, field := range data.Fields {
			if field.Column != column.Name {
				continue
			}

			if role, ok := managed[field.Name]; ok && role != "" {
				return fmt.Errorf("field %s is %s, which TSQ writes itself; it cannot be %s", field.Name, role, column.Fill)
			}
		}
	}

	return nil
}

func validateFieldDatabaseType(field genmodel.FieldInfo, keywordFields map[string]struct{}) error {
	if field.Type.Package.Path == "" {
		switch field.Type.TypeName {
		case "complex64", "complex128", "uintptr":
			return fmt.Errorf("type %s is not supported for generated columns", field.Type.TypeName)
		}
	}

	if field.IsSlice {
		if field.Type.Package.Path != "" || field.Type.TypeName != primitiveByte {
			return errors.New("slice/array columns must use []byte")
		}
	}

	if _, ok := keywordFields[field.Name]; ok {
		if field.IsPointer {
			return errors.New("keyword fields cannot be pointers")
		}

		if field.IsSlice {
			return errors.New("search fields must be of type string")
		}

		// tsq.Searchable accepts ~string columns, and LIKE on anything else is not
		// portable (PostgreSQL has no LIKE for integers).
		if field.Type.Package.Path != "" || field.Type.TypeName != "string" {
			return errors.New("search fields must be of type string")
		}
	}

	return nil
}

func isIntegerFieldType(field genmodel.FieldInfo) bool {
	if field.Type.Package.Path != "" {
		return false
	}

	switch field.Type.TypeName {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", primitiveUInt64:
		return true
	default:
		return false
	}
}

func writeGeneratedFile(filename string, src []byte) error {
	if err := ensureWritableGeneratedFile(filename); err != nil {
		return err
	}

	perm := os.FileMode(0o644)
	if info, err := os.Stat(filename); err == nil {
		perm = info.Mode().Perm()
	} else if !os.IsNotExist(err) {
		return err
	}

	dir := filepath.Dir(filename)
	pattern := "." + filepath.Base(filename) + ".tmp-*"

	tmpFile, err := os.CreateTemp(dir, pattern)
	if err != nil {
		return err
	}

	tmpName := tmpFile.Name()

	cleanup := func() {
		_ = os.Remove(tmpName)
	}
	defer cleanup()

	if err := tmpFile.Chmod(perm); err != nil {
		_ = tmpFile.Close()
		return err
	}

	if _, err := tmpFile.Write(src); err != nil {
		_ = tmpFile.Close()
		return err
	}

	if err := tmpFile.Close(); err != nil {
		return err
	}

	if err := os.Rename(tmpName, filename); err != nil {
		return err
	}

	return nil
}

func ensureWritableGeneratedFile(filename string) error {
	existing, err := os.ReadFile(filename)
	if os.IsNotExist(err) {
		return nil
	}

	if err != nil {
		return err
	}

	if len(existing) == 0 || bytes.HasPrefix(existing, []byte(generatedFileHeaderPrefix)) {
		return nil
	}

	return fmt.Errorf("refusing to overwrite non-generated file: %s", filename)
}

// stableVersion returns a version string suitable for embedding in generated
// file headers.  It strips the git-describe suffixes (-N-gHASH and -dirty)
// so that regenerating the same source at different commits always produces an
// identical header, allowing the CI "ensure generated examples are committed"
// check to pass.
//
// Examples:
//
//	"v1.2.0-10-ga3683ff-dirty" → "v1.2.0"
//	"v1.2.0-dirty"             → "v1.2.0"
//	"v1.2.0-10-ga3683ff"       → "v1.2.0"
//	"v1.2.0"                   → "v1.2.0"
//	"v1.2.0-beta.1"            → "v1.2.0-beta.1"  (pre-release: no git suffix)
//	"dev"                      → "dev"
func stableVersion(v string) string {
	// Strip -dirty suffix.
	v = strings.TrimSuffix(v, "-dirty")

	// Strip -N-gHASH suffix produced by `git describe --long`.
	// The pattern is: dash, one-or-more digits, dash, 'g', hex digits, end.
	for {
		prefix, suffix, found := strings.CutLast(v, "-")
		if !found {
			break
		}

		// Matches "g<hexchars>" (git abbreviated hash)
		if len(suffix) > 1 && suffix[0] == 'g' {
			allHex := true

			for _, c := range suffix[1:] {
				if c < '0' || c > '9' && (c < 'a' || c > 'f') {
					allHex = false
					break
				}
			}

			if allHex {
				v = prefix
				continue
			}
		}

		// Matches all-digit segment (commit count between tag and hash)
		allDigit := true

		for _, c := range suffix {
			if c < '0' || c > '9' {
				allDigit = false
				break
			}
		}

		if allDigit {
			v = prefix
			continue
		}

		break
	}

	return v
}
