#!/usr/bin/env python3
"""确认 examples/academy 的生成物就是当前源码此刻会产出的东西。

`git diff --exit-code -- examples/academy` 不能用来判断这件事：一波变更本来就可能
合法地改动生成物，而它们在提交之前一直是未提交状态——那道门会对每一波正当改动都失败。

判据只能是"拿当前源码重新渲染一遍，看结果一不一样"。`tsq gen --check` 正是为此存在：
它在内存里渲染并与磁盘比对，不落盘。它失败意味着两件事之一——有人手改了 `*.tsq.go`，
或者改完模板/解析器/示例结构体忘了跑 `make examples`。两种情况的修法都是 `make examples`
然后把结果一起提交。

注意生成文件头带着 TSQ 版本号（`// Code generated by tsq-vX.Y.Z.`），所以**改了
internal/buildinfo 的版本号也必须重新生成示例**，否则这道门会失败。发版流程依赖这
一点来保证 tag 和生成物是一致的。
"""

from __future__ import annotations

import subprocess
import sys
from typing import Final

from changeset import PROJECT_ROOT, ChangesetError, git_output

EXAMPLE_PACKAGE: Final = "examples/academy"


class GeneratedError(RuntimeError):
    """生成物与源码脱节时抛出。"""


def module_path() -> str:
    for line in (PROJECT_ROOT / "go.mod").read_text(encoding="utf-8").splitlines():
        fields = line.strip().split()
        if len(fields) == 2 and fields[0] == "module":
            return fields[1]

    raise GeneratedError("go.mod 里没有 module 指令")


def run(command: list[str]) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        command, cwd=PROJECT_ROOT, check=False, capture_output=True
    )


def main() -> int:
    built = run(["make", "--no-print-directory", "build"])
    if built.returncode != 0:
        detail = built.stderr.decode("utf-8", errors="replace").strip()
        raise GeneratedError(f"构建 tsq CLI 失败：\n{detail}")

    package = f"{module_path()}/{EXAMPLE_PACKAGE}"
    checked = run(["./bin/tsq", "gen", "--check", package])
    output = (checked.stdout + checked.stderr).decode("utf-8", errors="replace").strip()
    if checked.returncode == 0:
        print(f"生成物检查通过：{EXAMPLE_PACKAGE} 就是当前源码的输出。")

        return 0

    print(f"{EXAMPLE_PACKAGE} 的生成物与源码脱节：\n{output}")
    print(
        "\n跑 `make examples` 重新生成，然后 `./bin/examples/full-suite` 确认示例仍"
        "可运行，把生成结果一起提交。如果你是手改了 *.tsq.go，把改动挪回结构体、"
        "模板或解析器里——生成文件不是源码。"
    )

    return 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (GeneratedError, ChangesetError) as error:
        print(f"生成物检查失败：{error}", file=sys.stderr)
        raise SystemExit(1) from error
